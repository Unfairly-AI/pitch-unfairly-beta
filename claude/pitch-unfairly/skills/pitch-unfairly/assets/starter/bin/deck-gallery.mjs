// Every slide toolbox layout as one deck, in this project's brand:
//   npm run deck:gallery [-- <out>] [--wire] [--kit <folder>] [--photos <folder|a,b>] [--faces <folder|a,b>] [--no-shots] [--audit [--quick]]
// Each layout in slide-toolbox/catalog.json is built with its props from
// slide-toolbox/example.json (an array there shows it once per entry), with a
// label naming it and its job, into dist-gallery/ (dist-gallery-wire/ with
// --wire, which renders it as a wireframe: greys and the system font). Then it
// screenshots every slide headless, on the stage (the PDF render) and on a
// phone, and writes contact sheets beside the page: contact-sheet.png and
// contact-sheet-mobile.png. It reads brand/ and src/ and touches nothing there.
// --kit <folder> renders it in another brand: the folder holds a brand-kit@1
// brand.json and its files at their paths, and becomes this build's brand/,
// applied as npm run brand:apply would, into dist-gallery-<folder name>/.
// --audit then runs bin/audit.mjs --gallery against the built gallery: every
// check a deck gets, without this deck's guard, story or audit stamp.
// --photos <folder or a,b,c> puts real photos in place of the example's
// stand-ins (every layout with a photo prop, in turn), served at
// slide-toolbox/try/, and --faces <...> does the same for people's portraits
// (the photos when it's left out): a layout's
// crops and its contrast over an image are only judged with real ones.
import { cp, mkdir, mkdtemp, readdir, readFile, realpath, rm, symlink, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const TOOLBOX = fileURLToPath(new URL('../slide-toolbox/', import.meta.url));

/** The catalog, the example, and each built layout's gallery entries, in catalog order. */
export async function loadToolbox(toolbox = TOOLBOX) {
  const catalog = JSON.parse(await readFile(join(toolbox, 'catalog.json'), 'utf8'));
  const example = JSON.parse(await readFile(join(toolbox, 'example.json'), 'utf8'));
  const entries = [];
  for (const layout of catalog.layouts) {
    const props = [].concat(example.slides?.[layout.name] ?? []);
    if (!props.length) throw new Error(`example.json has no slides["${layout.name}"]; every layout needs its worked example.`);
    props.forEach((p, i) => entries.push({ layout, props: p, id: props.length > 1 ? `${layout.name}-${i + 1}` : layout.name }));
  }
  return { catalog, example, entries };
}

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** The gallery deck's index.astro: a label, then the layout with its example props, for each entry. */
export function galleryPage(entries, { wire = false } = {}) {
  const names = [...new Set(entries.map((e) => e.layout.name))];
  const imports = names.map((n, i) => `import L${i} from '../../slide-toolbox/layouts/${n}.astro';`).join('\n');
  const body = entries.map((e) => {
    const k = names.indexOf(e.layout.name);
    const tone = e.props.tone ?? e.layout.default_tone ?? 'paper';
    return `  <div class="gallery-tag" data-layout="${esc(e.layout.name)}"><b>${esc(e.layout.name)}</b><span>${esc(e.layout.job)}</span><i>${esc(tone)}</i></div>
  <L${k} {...props[${JSON.stringify(e.id)}]} id=${JSON.stringify(e.id)} label=${JSON.stringify(e.layout.name)} />`;
  }).join('\n');
  const props = Object.fromEntries(entries.map((e) => [e.id, e.props]));
  return `---
// Generated by bin/deck-gallery.mjs. Not a deck: the slide toolbox's layouts with example.json's props.
import Deck from '../layouts/Deck.astro';
${imports}
const props = ${JSON.stringify(props, null, 2)};
---

<Deck title="Slide toolbox gallery${wire ? ' (wireframe)' : ''}">
${body}
</Deck>

<style is:global>
  .gallery-tag { display: flex; flex-wrap: wrap; gap: 4px 16px; align-items: baseline; padding: 14px 24px; background: var(--ink); color: var(--paper); font: 500 14px/1.4 var(--font-body); }
  .gallery-tag b { font: 700 13px/1 var(--font-mono); letter-spacing: .08em; }
  .gallery-tag span { opacity: .8; }
  .gallery-tag i { margin-left: auto; font: 500 12px/1 var(--font-mono); opacity: .6; font-style: normal; }
  html.is-pdf .gallery-tag { display: none; }
</style>
`;
}

// Fontsource packages a --kit names that this project's node_modules lacks go
// here, not into node_modules: that folder is often a shared engine install.
const FONT_CACHE = join(tmpdir(), 'deck-gallery-fonts');

/**
 * node_modules for a --kit build: this project's packages linked one by one,
 * plus the kit's Fontsource packages from FONT_CACHE when the project lacks them.
 */
async function kitNodeModules(root, tmp, kit) {
  const { kitFaces } = await import('./brand-lib.mjs');
  const src = join(root, 'node_modules');
  const dest = join(tmp, 'node_modules');
  const packages = [...new Set(kitFaces(kit).filter((t) => t?.source === 'fontsource' && t.package).map((t) => t.package))];
  const missing = packages.filter((p) => !existsSync(join(src, p, 'package.json')));
  if (!missing.length) return symlink(src, dest);
  const uncached = missing.filter((p) => !existsSync(join(FONT_CACHE, 'node_modules', p, 'package.json')));
  if (uncached.length) {
    await mkdir(FONT_CACHE, { recursive: true });
    // Saved in the cache's own package.json: an unsaved install prunes the fonts an earlier kit installed.
    if (!existsSync(join(FONT_CACHE, 'package.json'))) await writeFile(join(FONT_CACHE, 'package.json'), '{ "private": true }\n');
    console.log(`Installing ${uncached.join(', ')} for the gallery`);
    execFileSync('npm', ['install', '--prefix', FONT_CACHE, '--save', '--no-audit', '--no-fund', ...uncached], { stdio: ['ignore', 'ignore', 'inherit'] });
  }
  await mkdir(dest);
  const scopes = new Set(missing.map((p) => p.split('/')[0]));
  for (const name of await readdir(src)) {
    if (scopes.has(name)) {
      await mkdir(join(dest, name));
      for (const pkg of await readdir(join(src, name))) await symlink(join(src, name, pkg), join(dest, name, pkg));
    } else await symlink(join(src, name), join(dest, name));
  }
  for (const p of missing) {
    if (!existsSync(join(dest, p.split('/')[0]))) await mkdir(join(dest, p.split('/')[0]));
    await symlink(join(FONT_CACHE, 'node_modules', p), join(dest, p));
  }
}

const IMAGE = /\.(jpe?g|png|webp|avif)$/i;

/** Image files from a folder or a comma-separated list. */
export async function imageList(arg) {
  if (!arg) return [];
  const one = resolve(arg);
  if (existsSync(one) && !IMAGE.test(one)) return (await readdir(one)).filter((f) => IMAGE.test(f)).sort().map((f) => join(one, f));
  return arg.split(',').map((f) => resolve(f.trim())).filter(Boolean);
}

/**
 * The entries with real images in place of the example's: each layout's `photo`
 * and each person's portrait, taken in turn from `photos` and `faces`, served
 * at slide-toolbox/try/ and slide-toolbox/try-faces/ as <n>-<name>.
 */
export function withPhotos(entries, photos = [], faces = photos) {
  if (!photos.length && !faces.length) return entries;
  const url = (f, i, dir = 'try') => `slide-toolbox/${dir}/${i}-${basename(f)}`;
  let p = 0;
  let q = 0;
  return entries.map((e) => {
    const props = { ...e.props };
    if (photos.length && 'photo' in (e.layout.props ?? {})) props.photo = url(photos[p % photos.length], p++ % photos.length);
    if (faces.length && Array.isArray(props.people)) props.people = props.people.map((x) => ({ ...x, photo: url(faces[q % faces.length], q++ % faces.length, 'try-faces') }));
    return { ...e, props };
  });
}

/** Build the gallery into `out`, in this project's brand or the kit folder `kit`. Returns { out, entries }. */
export async function buildDeckGallery({ root = '.', out, wire = false, kit, toolbox = TOOLBOX, photos = [], faces = photos } = {}) {
  root = resolve(root);
  if (kit) {
    kit = resolve(kit);
    if (!existsSync(join(kit, 'brand.json'))) throw new Error(`${kit} has no brand.json. --kit takes a folder holding a brand-kit@1 brand.json and its files.`);
  }
  out = resolve(root, out ?? (kit ? `dist-gallery-${basename(kit)}` : wire ? 'dist-gallery-wire' : 'dist-gallery'));
  if (!kit && !existsSync(join(root, 'src/brand/brand.css'))) throw new Error('src/brand/brand.css is missing. Run npm run brand:apply first.');
  const entries = withPhotos((await loadToolbox(toolbox)).entries, photos, faces);
  // The real path: on macOS tmpdir() is a symlink, and Astro's compiler keys its cache by real path.
  const tmp = await realpath(await mkdtemp(join(tmpdir(), 'deck-gallery-')));
  const env = { DECK_WIRE: process.env.DECK_WIRE, ASTRO_TELEMETRY_DISABLED: process.env.ASTRO_TELEMETRY_DISABLED };
  try {
    for (const f of ['src', 'brand', 'public']) if (existsSync(join(root, f))) await cp(join(root, f), join(tmp, f), { recursive: true });
    for (const f of ['astro.config.mjs', 'package.json', 'tsconfig.json']) if (existsSync(join(root, f))) await cp(join(root, f), join(tmp, f));
    await cp(toolbox, join(tmp, 'slide-toolbox'), { recursive: true });
    // The example's sample photos and screenshots (slide-toolbox/assets/), served beside the page:
    // example.json says "slide-toolbox/<file>".
    if (existsSync(join(toolbox, 'assets'))) await cp(join(toolbox, 'assets'), join(tmp, 'public/slide-toolbox'), { recursive: true });
    for (const [list, dir] of [[photos, 'try'], [faces, 'try-faces']]) {
      await mkdir(join(tmp, 'public/slide-toolbox', dir), { recursive: true });
      for (const [i, f] of list.entries()) await cp(f, join(tmp, 'public/slide-toolbox', dir, `${i}-${basename(f)}`));
    }
    if (kit) {
      // The kit is this build's brand/, applied as npm run brand:apply applies a deck's.
      await rm(join(tmp, 'brand'), { recursive: true, force: true });
      await cp(kit, join(tmp, 'brand'), { recursive: true, dereference: true });
      await kitNodeModules(root, tmp, JSON.parse(await readFile(join(kit, 'brand.json'), 'utf8')));
      try {
        execFileSync(process.execPath, [join(root, 'bin/brand-apply.mjs')], { cwd: tmp, stdio: ['ignore', 'pipe', 'pipe'] });
      } catch (e) {
        throw new Error(`brand apply failed for ${kit}:\n${String(e.stdout ?? '')}${String(e.stderr ?? '')}`.trim());
      }
    } else await symlink(join(root, 'node_modules'), join(tmp, 'node_modules'));
    await rm(join(tmp, 'src/pages'), { recursive: true, force: true });
    await mkdir(join(tmp, 'src/pages'));
    await writeFile(join(tmp, 'src/pages/index.astro'), galleryPage(entries, { wire }));
    // Deck.astro reads DECK_WIRE while it renders; the build runs in this process.
    process.env.DECK_WIRE = wire ? '1' : '';
    process.env.ASTRO_TELEMETRY_DISABLED = '1';
    const { build } = await import('astro');
    // Astro's and Vite's caches go in the temp folder: node_modules may be shared by builds running at once.
    await build({ root: tmp, outDir: join(tmp, 'dist'), cacheDir: join(tmp, '.astro-cache'), logLevel: 'error', vite: { cacheDir: join(tmp, '.vite') } });
    await rm(out, { recursive: true, force: true });
    await cp(join(tmp, 'dist'), out, { recursive: true, dereference: true });
    return { out, entries };
  } finally {
    for (const [k, v] of Object.entries(env)) if (v === undefined) delete process.env[k]; else process.env[k] = v;
    await rm(tmp, { recursive: true, force: true });
  }
}

/**
 * Screenshot every slide of a built gallery, as bin/shots.mjs does a deck: the
 * stage at the PDF render (?pdf=1, 960x540 per slide) and a 393-wide phone,
 * then a contact sheet of each. Returns the two sheet paths.
 */
export async function galleryShots(dir) {
  const [{ default: puppeteer }, { serveDir }, { settleForShots, stableLaunch }, { refuseInCodexSandbox }] = await Promise.all([
    import('puppeteer'), import('./serve.mjs'), import('./stable-shots.mjs'), import('./browser-guard.mjs'),
  ]);
  refuseInCodexSandbox('The gallery contact sheet');
  const server = await serveDir(dir);
  const browser = await puppeteer.launch(stableLaunch());
  const HIDE = '.deck-nav, .deck-notes, .gallery-tag { display: none !important; }';
  try {
    const capture = async (name, viewport, query) => {
      const shots = join(dir, 'shots', name);
      await mkdir(shots, { recursive: true });
      const page = await browser.newPage();
      await page.setViewport(viewport);
      await page.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }]);
      await page.goto(`${server.url}/${query}`, { waitUntil: 'networkidle0' });
      await page.waitForFunction(() => window.__deckReady === true, { timeout: 15000 }).catch(() => {});
      await page.addStyleTag({ content: HIDE });
      await settleForShots(page);
      const ids = await page.$$eval('.slide', (s) => s.map((x) => x.id));
      const files = [];
      for (const [i, id] of ids.entries()) {
        const file = join(shots, `${String(i + 1).padStart(2, '0')}-${id.replace(/^slide-/, '')}.png`);
        await page.evaluate((id) => document.getElementById(id).scrollIntoView(), id);
        await (await page.$(`[id="${id}"]`)).screenshot({ path: file });
        files.push(file);
      }
      await page.close();
      return files;
    };
    const sheet = async (files, file, columns, width) => {
      const imgs = await Promise.all(files.map(async (f) => `data:image/png;base64,${(await readFile(f)).toString('base64')}`));
      const page = await browser.newPage();
      await page.setViewport({ width: columns * width + (columns + 1) * 16, height: 400 });
      await page.setContent(`<body style="margin:0;padding:16px;background:#222;display:grid;grid-template-columns:repeat(${columns},${width}px);gap:16px;font:12px monospace;color:#bbb">
        ${imgs.map((src, i) => `<figure style="margin:0"><img src="${src}" style="width:100%;display:block;outline:1px solid #444"><figcaption style="padding-top:4px">${esc(files[i].split('/').pop().replace(/\.png$/, ''))}</figcaption></figure>`).join('')}
      </body>`);
      await page.screenshot({ path: file, fullPage: true });
      await page.close();
      return file;
    };
    const [stage, mobile] = await Promise.all([
      capture('stage', { width: 1920, height: 1080, deviceScaleFactor: 0.5 }, '?pdf=1'),
      capture('mobile', { width: 393, height: 745, isMobile: true, hasTouch: true, deviceScaleFactor: 1 }, ''),
    ]);
    return {
      stage: await sheet(stage, join(dir, 'contact-sheet.png'), 2, 640),
      mobile: await sheet(mobile, join(dir, 'contact-sheet-mobile.png'), Math.min(mobile.length, 6), 197),
    };
  } finally {
    await browser.close();
    await server.close();
  }
}

/**
 * Audit a built gallery as a deck: serve it and run bin/audit.mjs --gallery
 * from `root`, so the source checks read slide-toolbox/layouts/. Resolves to
 * the audit's exit code.
 */
export async function auditGallery(dir, { root = '.', quick = false } = {}) {
  const { spawn } = await import('node:child_process');
  const { serveDir } = await import('./serve.mjs');
  const server = await serveDir(dir);
  try {
    return await new Promise((ok, fail) => {
      const child = spawn(process.execPath, [join(resolve(root), 'bin/audit.mjs'), server.url, '--gallery', ...(quick ? ['--quick'] : [])], { cwd: resolve(root), stdio: 'inherit' });
      child.on('error', fail);
      child.on('exit', (code) => ok(code ?? 1));
    });
  } finally {
    await server.close();
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const wire = args.includes('--wire');
  const k = args.indexOf('--kit');
  const kit = k >= 0 ? args[k + 1] : undefined;
  if (k >= 0 && (!kit || kit.startsWith('--'))) {
    console.error('✗ --kit takes a folder: npm run deck:gallery -- --kit ../kits/acme');
    process.exit(1);
  }
  const value = (flag) => (args.includes(flag) ? args[args.indexOf(flag) + 1] : undefined);
  const taken = new Set(['--kit', '--photos', '--faces'].filter((f) => args.includes(f)).map((f) => args.indexOf(f) + 1));
  const out = args.find((a, i) => !a.startsWith('--') && !taken.has(i));
  try {
    const photos = await imageList(value('--photos'));
    const faces = value('--faces') ? await imageList(value('--faces')) : photos;
    for (const f of [...photos, ...faces]) if (!existsSync(f)) throw new Error(`${f} doesn't exist. --photos and --faces take a folder of images or a comma-separated list.`);
    const r = await buildDeckGallery({ out, wire, kit, photos, faces });
    console.log(`Built ${r.out}/index.html: ${r.entries.length} slides from ${new Set(r.entries.map((e) => e.layout.name)).size} layouts${wire ? ' as a wireframe' : kit ? ` in ${basename(resolve(kit))}'s brand` : ' in this brand'}.`);
    if (!args.includes('--no-shots')) {
      const sheets = await galleryShots(r.out);
      console.log(`contact sheet: ${sheets.stage}\ncontact sheet (phone): ${sheets.mobile}`);
    }
    if (args.includes('--audit')) process.exitCode = await auditGallery(r.out, { quick: args.includes('--quick') });
  } catch (e) {
    console.error(`✗ ${e.message}`);
    process.exit(1);
  }
}
