// Upload a built deck to the signed URLs a host returned.
// Usage: node bin/upload.mjs uploads.json [dist]
// uploads.json is the host's response (or just its "uploads" array):
// [{ path, upload_url, content_type }, ...]
import { readFile } from 'node:fs/promises';
import { basename, join, resolve } from 'node:path';

const [listFile, dir = 'dist'] = process.argv.slice(2).filter((a) => !a.startsWith('--'));
if (!listFile) {
  console.error('Usage: node bin/upload.mjs uploads.json [dist]');
  process.exit(2);
}
// Publishing a deck needs a design review newer than every edit, with every
// slide marked ready (SKILL step 5). Review uploads (artifacts) skip this.
if (basename(resolve(dir)) === 'dist') {
  const { stat, readdir } = await import('node:fs/promises');
  const review = JSON.parse(await readFile('artifacts/review.json', 'utf8').catch(() => 'null'));
  const newest = async (path) => {
    const s = await stat(path).catch(() => null);
    if (!s) return 0;
    if (!s.isDirectory()) return s.mtimeMs;
    // brand/capture is evidence and src/brand is regenerated by every build, so neither counts as an edit.
    const times = await Promise.all((await readdir(path)).filter((n) => n !== 'capture' && join(path, n) !== join('src', 'brand')).map((n) => newest(join(path, n))));
    return Math.max(s.mtimeMs, ...times);
  };
  const lastEdit = Math.max(await newest('src'), await newest('brand'), await newest('story.md'));
  const problem = !review
    ? 'there is no design review (artifacts/review.json)'
    : review.ready_to_publish !== true
      ? `the last review marked ${review.slides?.filter((s) => s.verdict !== 'ship').length ?? 'some'} slide(s) to fix`
      : new Date(review.reviewed_at).getTime() < lastEdit
        ? 'files changed after the last review'
        : null;
  if (problem) {
    console.error(`Not publishing: ${problem}. Run npm run shots, then deck_review_start and deck_review (SKILL step 5), fix what it marks, and review again.`);
    process.exit(1);
  }
}

const parsed = JSON.parse(await readFile(listFile, 'utf8'));
const uploads = Array.isArray(parsed) ? parsed : parsed.uploads;
if (!Array.isArray(uploads)) throw new Error(`${listFile} has no uploads list`);

let next = 0;
const failed = [];
async function worker() {
  while (next < uploads.length) {
    const { path, upload_url, content_type } = uploads[next++];
    const body = await readFile(join(dir, path));
    let response;
    for (let attempt = 1; attempt <= 3; attempt++) {
      response = await fetch(upload_url, { method: 'PUT', headers: { 'Content-Type': content_type }, body });
      // A retry after a lost response finds the file already stored.
      if (response.ok || (attempt > 1 && response.status === 409)) break;
    }
    if (!response.ok && response.status !== 409) failed.push(`${path}: HTTP ${response.status} ${await response.text().catch(() => '')}`.slice(0, 300));
  }
}
await Promise.all(Array.from({ length: 6 }, worker));

if (failed.length) {
  console.error(`${failed.length} of ${uploads.length} uploads failed:`);
  failed.forEach((f) => console.error(`  ✗ ${f}`));
  process.exitCode = 1;
} else {
  console.log(`Uploaded ${uploads.length} files.`);
}
