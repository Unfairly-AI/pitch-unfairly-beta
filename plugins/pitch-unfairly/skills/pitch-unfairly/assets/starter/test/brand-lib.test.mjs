test('validation of the rich sections: color refs, texture names, limits, enums, paths', () => {
  const errs = (mutate) => { const kit = rich(); mutate(kit); return validateKit(kit).join('\n'); };
  assert.match(errs((k) => { k.palette.gradients[0].stops[0].color = 'terracotta'; }), /gradients\[0\]\.stops\[0\]\.color: "terracotta" is not a hex, a palette role, or a palette\.extras name/);
  assert.match(errs((k) => { k.palette.applications[0].colors.push('nope'); }), /applications\[0\]\.colors\[3\]/);
  assert.match(errs((k) => { k.elements[0].color = 'sky'; }), /elements\[0\]\.color/);
  assert.match(errs((k) => { k.textures[1].tint = '#12'; }), /textures\[1\]\.tint/);
  assert.match(errs((k) => { k.elements[4].texture = 'marble'; }), /elements\[4\]\.texture: "marble" is not one of the kit's textures/);
  assert.match(errs((k) => { k.palette.extras = Array.from({ length: 25 }, (_, i) => ({ name: `c${i}`, hex: '#000000' })); }), /palette\.extras has 25 entries; the limit is 24/);
  assert.match(errs((k) => { k.rules = Array.from({ length: 41 }, () => 'A rule.'); }), /rules has 41 entries; the limit is 40/);
  assert.match(errs((k) => { k.palette.gradients[0].stops = [{ color: 'ink' }]; }), /stops needs 2 to 6 stops/);
  assert.match(errs((k) => { k.identity.lockups[0].use = 'x'.repeat(301); }), /lockups\[0\]\.use is 301 characters; the limit is 300/);
  assert.match(errs((k) => { k.identity.lockups[0].background = 'medium'; }), /lockups\[0\]\.background must be light, dark, any/);
  assert.match(errs((k) => { k.elements[0].kind = 'swoosh'; }), /elements\[0\]\.kind must be frame, bracket/);
  assert.match(errs((k) => { k.textures[0].blend = 'darken'; }), /textures\[0\]\.blend must be normal, multiply/);
  assert.match(errs((k) => { k.typography.roles.eyebrow.case = 'smallcaps'; }), /roles\.eyebrow\.case must be none, uppercase, lowercase/);
  assert.match(errs((k) => { k.typography.roles.eyebrow.tracking = 0.9; }), /roles\.eyebrow\.tracking must be a number from -0\.2 to 0\.5/);
  assert.match(errs((k) => { k.typography.roles.code = { font: 'mono' }; }), /roles\.code\.font is "mono", and the kit has no typography\.mono/);
  assert.match(errs((k) => { k.palette.gradients[1].angle = 45; }), /angle is for linear gradients only/);
  assert.match(errs((k) => { k.elements[0].weight = 80; }), /elements\[0\]\.weight must be a number from 0 to 64/);
  assert.match(errs((k) => { k.textures[0].path = '../secret.png'; }), /textures\[0\]\.path: bad path/);
  assert.match(errs((k) => { k.identity.lockups[1].path = 'logos/master.pdf'; }), /must be an image/);
  assert.match(errs((k) => { k.elements[1].name = 'Quote Bracket'; }), /elements\[1\]\.name must be kebab-case/);
  assert.match(errs((k) => { k.textures[1].name = 'clay-grain'; }), /textures: the name "clay-grain" is used twice/);
  assert.match(errs((k) => { k.messaging.taglines.push('x'.repeat(161)); }), /messaging\.taglines\[2\] is 161 characters/);
  assert.match(errs((k) => { k.messaging.key_messages[0].headline = ''; }), /key_messages\[0\]\.headline is required/);
  assert.match(errs((k) => { k.palette.extras[0].group = 'Primary Colors'; }), /extras\[0\]\.group must be kebab-case/);
});

