// assets.ts as brand-apply wrote it for the starter's kit before the rich sections existed.
const ASSETS_BEFORE = `// Generated by \`npm run brand:apply\`. Edit brand/brand.json instead.

export const brandName = "Pitch Unfairly";
export const wordmark = "Pitch Unfairly";
export const logos: Record<string, string> = {  };
export const imagery: { url: string; role: string; alt: string; notes: string }[] = [
];
`;

test('ACCEPTANCE: a kit without the rich sections generates byte-identical brand.css and fonts.ts, and assets.ts only gains empty exports', () => {
  const kit = JSON.parse(read('brand/brand.json'));
  assert.deepEqual(validateKit(kit), []);
  assert.equal(brandCss(kit, fontFaceCss(kit, '../../brand/'), '../../brand/'), read('src/brand/brand.css'));
  assert.equal(brandCss(kit, fontFaceCss(kit, '../../brand/')), read('src/brand/brand.css'), 'the relPrefix default changes nothing');
  assert.equal(fontImports(kit), read('src/brand/fonts.ts'));
  const mod = assetModule(kit, '../../brand/');
  assert.equal(mod, read('src/brand/assets.ts'), 'the committed assets.ts is current');
  assert.ok(mod.startsWith(ASSETS_BEFORE), 'everything assets.ts exported before is unchanged');
  const added = mod.slice(ASSETS_BEFORE.length);
  assert.doesNotMatch(added, /^import /m, 'no new imports');
  for (const name of ['lockups', 'textures', 'elements', 'typeRoles', 'gradients', 'messaging']) assert.match(added, new RegExp(`export const ${name}\\b`));
  assert.match(added, /export const lockups: [^=]+= \[\n\];/);
  assert.match(added, /export const typeRoles: string\[\] = \[\];/);
  assert.match(added, /"essence":"","taglines":\[\],"key_messages":\[\],"attributes":\[\]/);
  // And brand.css for the minimal kit, too: no rich block at all.
  assert.doesNotMatch(brandCss(base()), /--g-|--type-|--tex-|\.el-|\.type-/);
});

