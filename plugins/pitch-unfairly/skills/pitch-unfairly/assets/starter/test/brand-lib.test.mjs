test('gradients and type roles become tokens and classes', () => {
  const css = brandCss(rich());
  assert.match(css, /--g-firing: linear-gradient\(120deg, var\(--c-clay\) 0%, var\(--c-glaze\) 100%\);/);
  assert.match(css, /--g-kiln-glow: radial-gradient\(circle, #e9b949, var\(--accent\), var\(--ink\)\);/, 'stops without at are left to the browser');
  assert.match(css, /--type-eyebrow-font: var\(--font-body\);/);
  assert.match(css, /--type-eyebrow-tracking: 0\.14em;/);
  assert.match(css, /--type-eyebrow-case: uppercase;/);
  assert.match(css, /--type-quote-style: italic;/);
  assert.match(css, /--type-quote-line: 1\.2;/);
  assert.match(css, /\.type-quote \{\n  font-family: var\(--type-quote-font\);\n  font-weight: var\(--type-quote-weight\);\n  font-style: var\(--type-quote-style\);\n  line-height: var\(--type-quote-line\);\n  font-size: calc\(1em \* var\(--type-quote-scale\)\);\n\}/);
  // Only the properties a role sets: headline has no case, style, or scale.
  const headline = /\.type-headline \{[^}]*\}/.exec(css)[0];
  assert.doesNotMatch(headline, /text-transform|font-style|font-size/);
  assert.match(headline, /font-family: var\(--type-headline-font\);/);
});

