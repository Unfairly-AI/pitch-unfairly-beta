test('each element kind with CSS gets its class; the rest get none', () => {
  const css = brandCss(rich());
  assert.match(css, /\.el-photo-frame \{\n  border: 14px solid var\(--c-pine\);\n\}/);
  assert.match(css, /\.el-quote-bracket \{\n  position: relative;\n  padding-inline: 0\.9em;\n\}/);
  assert.match(css, /\.el-quote-bracket::before \{\n  left: 0;\n  border-left-width: 3px;\n  border-top-width: 3px;\n  border-bottom-width: 3px;\n\}/);
  assert.match(css, /\.el-quote-bracket::after \{\n  right: 0;\n  border-right-width: 3px;/);
  assert.match(css, /border: 0 solid var\(--c-clay\);/);
  assert.match(css, /\.el-glaze-bar \{\n  background: linear-gradient\(transparent 58%, var\(--c-glaze\) 58%\) no-repeat;\n  box-decoration-break: clone;\n  -webkit-box-decoration-break: clone;\n  padding-inline: 0\.08em;\n\}/);
  assert.match(css, /\.el-hairline \{\n  border: 0;\n  border-top: 1px solid var\(--c-ash\);\n\}/);
  assert.match(css, /\.el-grain-word \{\n  color: var\(--accent\);\n\}/, 'knockout fallback color');
  assert.match(css, /background: var\(--tex-clay-grain\) center \/ cover;\n    -webkit-background-clip: text;\n    background-clip: text;\n    color: transparent;/);
  assert.doesNotMatch(css, /el-stacked-headline/);
  // Defaults: a frame without weight or color is 12px accent; a rule is 2px border color.
  const kit = rich();
  kit.elements = [{ name: 'box', kind: 'frame' }, { name: 'line', kind: 'rule' }, { name: 'mark', kind: 'bar-under', weight: 30 }, { name: 'brk', kind: 'bracket' }];
  const d = brandCss(kit);
  assert.match(d, /\.el-box \{\n  border: 12px solid var\(--accent\);/);
  assert.match(d, /\.el-line \{\n  border: 0;\n  border-top: 2px solid var\(--border-color\);/);
  assert.match(d, /transparent 70%, var\(--highlight\) 70%/);
  assert.match(d, /border-left-width: 2px;/);
  assert.doesNotMatch(d, /undefined|null/);
});

